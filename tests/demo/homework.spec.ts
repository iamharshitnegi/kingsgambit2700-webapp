import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";

test("homework samples, student scope, puzzle resume and creation dialogs are accessible", async ({ page }, info) => {
  await page.goto("/demo");
  await page.getByRole("button", { name: /student@example.test/ }).click();
  await expect(page).toHaveURL(/\/student$/);
  await page.goto("/student/homework");
  await expect(page.getByRole("heading", { name: "My homework.", exact: true })).toBeVisible();
  await expect(page.getByRole("combobox", { name: /Learner|Batch/ })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Create homework" })).toHaveCount(0);
  await expect(page.getByRole("button", { name: /Build a better thinking routine/ })).toHaveCount(0);
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.getByRole("searchbox", { name: "Search homework" }).fill("no matching challenge");
  await expect(page.getByRole("heading", { name: "No matching homework" })).toBeVisible();
  await page.getByRole("button", { name: "Clear filters" }).click();
  await page.getByRole("region", { name: "Suggested practice" }).getByRole("button", { name: "Continue practice" }).click();
  const practice = page.getByRole("dialog", { name: "The art of the checkmate" });
  await expect(practice.getByLabel("Puzzle", { exact: true })).toHaveValue("2");
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await practice.getByLabel("Your move", { exact: true }).fill("Ra8#");
  await practice.getByRole("button", { name: "Check move", exact: true }).click();
  await expect(practice.getByText("Solved — well done.", { exact: true })).toBeVisible();
  await practice.getByRole("button", { name: "Continue later" }).click();
  await page.reload();
  await expect(page.getByRole("region", { name: "Suggested practice" })).toContainText("3 of 5 puzzles solved");
  await page.screenshot({ path: info.outputPath("homework.png"), fullPage: true });
  await page.goto("/demo");
  await page.getByRole("button", { name: /coach@example.test/ }).click();
  await expect(page).toHaveURL(/\/coach$/);
  await page.goto("/coach/homework");
  await page.getByRole("button", { name: "Create homework", exact: true }).click();
  const editor = page.getByRole("dialog", { name: "Create homework" });
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  expect(await editor.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await editor.getByRole("button", { name: "Study & reflect", exact: true }).click();
  await editor.getByRole("button", { name: "Continue", exact: true }).click();
  await editor.getByRole("checkbox", { name: "Aarav", exact: true }).check();
  await editor.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(editor.getByRole("button", { name: "Save draft", exact: true })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
});
